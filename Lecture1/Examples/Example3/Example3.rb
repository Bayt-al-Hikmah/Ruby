a = 10           # Integer
b = 4            # Integer
c = 4.0          # Float

#  arithmetic operations

puts a + b    # result: 14      Integer
puts a - b    # result: 6       Integer
puts a * b    # result: 40      Integer
puts a / b    # result: 2       Integer
puts a / c    # result: 2.5     Float
puts a % b    # result: 2       Integer
puts a ** c   # result: 10000.0 Float


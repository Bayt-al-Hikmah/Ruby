# Converting between Types

# Convert to Intenger
puts "42".to_i      # result 42
puts "hello".to_i   # result 0 

# Convert to Float
puts "3.14".to_f    # result 3.14
puts "10".to_f      # result 10.0
puts "Ali".to_f     # result 0.0

# Convert to String
puts 100.to_s       # result "100"
puts true.to_s      # result "true"
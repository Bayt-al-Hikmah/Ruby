# Comparison and Logical Operators

# Comparison Operators

puts 5 > 4    # Greater then          | result true
puts 4 < 2    # Lesser then           | result false
puts 4 == 4   # Equal to              | result true
puts 1 != 1   # Not equal to          | result false
puts 2 >= 2   # Greater then or equal | result true
puts 4 <= 5   # Less then or equal    | result true

# Logical Operators

puts true || false    # Logical or    | result true
puts true && false    # Logical and   | result false
puts !false           # Logical not   | result true